const ROLE_PERMISSIONS: Record<StaffRole, readonly Permission[]> = {
  SYSTEM_ADMIN,
  ORGANIZATION_ADMIN,
  RECEPTIONIST,
  REHABILITATION_SPECIALIST,
};

export function permissionsForRole(role: StaffRole): Permission[] {
  return [...ROLE_PERMISSIONS[role]];
}

export function roleHasPermission(role: StaffRole, permission: Permission): boolean {
  return ROLE_PERMISSIONS[role].includes(permission);
}

export function isKnownPermissionCatalogComplete(): boolean {
  return ALL.length > 0;
}
