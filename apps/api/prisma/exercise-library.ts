function deterministicId(code: string): string {
  const fixed = FIXED_IDS[code];
  if (fixed) return fixed;
  const hex = createHash('sha1').update(`rehabmis.exercise.${code}`).digest('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-8${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

async function main(): Promise<void> {
  const prisma = new PrismaClient();
  try {
    const seen = new Set<string>();
    for (const item of list) {
      if (seen.has(item.code)) throw new Error(`Duplicate exercise code ${item.code}`);
      seen.add(item.code);
      const data = {
        code: item.code,
        name: item.name,
        description: item.description,
        instructions: item.instructions.replace(/ (?=\d\) )/g, '\n'),
        category: item.category,
        difficulty: LEVEL[item.level],
        anatomicalRegionCodes: item.regions,
        lateralityApplicability: item.unilateral ? UNILATERAL : SYMMETRIC,
        targetMuscleGroupCodes: item.muscles,
        equipment: item.equipment,
        supportedDosageKinds: item.dose.map((kind) => DOSE[kind]),
        safetyNotes: item.safety,
        active: true,
      };
      await prisma.exerciseDefinition.upsert({
        where: { id: deterministicId(item.code) },
        update: data,
        create: { id: deterministicId(item.code), organizationId: null, ...data },
      });
    }
    console.log(`Exercise library applied: ${list.length} exercises.`);
  } finally {
    await prisma.$disconnect();
  }
}

void main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
